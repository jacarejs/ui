export const shippedComponents = componentMeta.map(([name, group, blurb]) => ({
  name,
  group,
  blurb,
}))

function sortGroupItems(group, items) {
  const order = componentSortOrder[group]
  if (!order?.length) {
    return items.slice().sort((a, b) => a.name.localeCompare(b.name))
  }
  const rank = new Map(order.map((name, index) => [name, index]))
  return items.slice().sort((a, b) => {
    const left = rank.has(a.name) ? rank.get(a.name) : Number.MAX_SAFE_INTEGER
    const right = rank.has(b.name) ? rank.get(b.name) : Number.MAX_SAFE_INTEGER
    if (left !== right) return left - right
    return a.name.localeCompare(b.name)
  })
}

export function componentsByGroup(hiddenNames = catalogHiddenComponents) {
  const hide = new Set(hiddenNames)
  const buckets = new Map()
  for (const item of shippedComponents) {
    if (hide.has(item.name)) continue
    const list = buckets.get(item.group) || []
    list.push(item)
    buckets.set(item.group, list)
  }
  return componentGroupOrder
    .filter((group) => (buckets.get(group) || []).length > 0)
    .map((group) => ({
      title: group,
      items: sortGroupItems(group, buckets.get(group) || []),
    }))
}

function componentNavSections() {
  return componentsByGroup(navHiddenComponents).map((group) => ({
    title: group.title,
    items: group.items.map((item) => ({
      href: componentHref(item.name),
      label: item.name,
      blurb: item.blurb,
    })),
  }))
}

